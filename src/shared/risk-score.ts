const RUSHED_TITLE_RE = /\b(hotfix|hot-fix|urgent|emergency|asap|quick ?fix|revert)\b/i;
const WIP_TITLE_RE = /(^\s*\[?wip\]?\b|\bdo not merge\b|\bdnm\b)/i;

const FACTOR_MAX: Record<RiskFactorKey, number> = {
  size: 20,
  spread: 10,
  sensitive: 40,
  patterns: 30,
  tests: 20,
  shape: 10,
  context: 10,
};
const FACTOR_KEYS = Object.keys(FACTOR_MAX) as RiskFactorKey[];
const FACTOR_LABEL: Record<RiskFactorKey, { ja: string; en: string }> = {
  size: { ja: "変更の規模", en: "Change size" },
  spread: { ja: "変更の広がり", en: "Change spread" },
  sensitive: { ja: "影響の大きい領域", en: "Sensitive areas" },
  patterns: { ja: "危ないコードのパターン", en: "Risky code patterns" },
  tests: { ja: "テストの不足", en: "Test coverage gap" },
  shape: { ja: "変更の形", en: "Change shape" },
  context: { ja: "作成者と経緯", en: "Author & context" },
};

const SEMANTIC_ITEM_MAX = 15;
const SEMANTIC_TOTAL_MAX = 20;
const ESCALATION_FLOOR = 60;

// ---------------------------------------------------------------------------
// 補助
// ---------------------------------------------------------------------------

function step(value: number, table: readonly [number, number][]): number {
  for (const [bound, points] of table) {
    if (value <= bound) return points;
  }
  return (table[table.length - 1] as [number, number])[1];
}

function truncate(text: string, n = 100): string {
  const s = text.trim();
  return s.length <= n ? s : `${s.slice(0, n - 1)}…`;
}

/** 秘密情報を画面やコメントにそのまま出さない */
function redact(text: string): string {
  return text.replace(/([A-Za-z0-9_-]{4})[A-Za-z0-9_\-/+=]{8,}/g, "$1••••");
}

function clamp(value: number, min: number, max: number): number {
  return Math.max(min, Math.min(max, value));
}

function listPaths(paths: readonly string[], n = 3): string {
  return paths.slice(0, n).join(", ") + (paths.length > n ? " …" : "");
}

interface ScoredFile {
  path: string;
  status: DiffFile["status"];
  additions: number;
  deletions: number;
  added: { line: number; text: string }[];
  binary: boolean;
  ignored: boolean;
  lockfile: boolean;
  generated: boolean;
  test: boolean;
  doc: boolean;
  code: boolean;
  workflow: boolean;
}

function classify(file: DiffFile, ignoredPaths: readonly string[]): ScoredFile {
  const path = file.path;
  const lower = path.toLowerCase();
  const added: ScoredFile["added"] = [];
  let deletions = 0;
  for (const hunk of file.hunks) {
    for (const line of hunk.lines) {
      if (line.type === "add") added.push({ line: line.newLine ?? 0, text: line.content });
      else if (line.type === "del") deletions++;
    }
  }
  const lockfile = LOCKFILE_RE.test(lower);
  let generated = GENERATED_RE.test(lower);
  const test = TEST_RE.test(path);
  const doc = DOC_RE.test(lower) && !test;
  // 生成器が付ける「DO NOT EDIT」の印があれば、手で書いたコードとして数えない
  if (
    !generated &&
    GENERATED_HEADER_RE.test(
      added
        .slice(0, 12)
        .map((l) => l.text)
        .join(" "),
    )
  ) {
    generated = true;
  }
  return {
    path,
    status: file.status,
    additions: added.length,
    deletions,
    added,
    binary: file.isBinary,
    ignored: ignoredPaths.some((pattern) => compilePattern(pattern)?.test(path) === true),
    lockfile,
    generated,
    test,
    doc,
    code: CODE_EXT_RE.test(lower) && !(test || doc || generated),
    workflow: WORKFLOW_RE.test(lower),
  };
}

