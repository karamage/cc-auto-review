/**
 * PR の変更リスクを 0〜100 の点数にする。pr-risk-score スキルの採点モデルを移植したもの。
 *
 * 点数は 2 層でできている。
 * 1. 決定的な基準点（computeBaselineRisk）。同じ diff なら必ず同じ点になり、PR の文章で下げられない
 * 2. AI の意味的な補正（applySemanticRisk）。diff の意味を読んで ±20 まで動かす。
 *    引用付きの重大な仕組みを見つけたら「エスカレーション」として必ず人に回す
 *
 * 点数が閾値（既定 50）を超えたら、完全自動運転は人に回す
 */

export type RiskScoreLevel = "LOW" | "MEDIUM" | "HIGH" | "CRITICAL";

/** 下限の点と段階。上から順に見る。閾値 50 を「超えたら」人に回すので、HIGH は 51 から */
const LEVELS: readonly [number, RiskScoreLevel][] = [
  [76, "CRITICAL"],
  [51, "HIGH"],
  [25, "MEDIUM"],
  [0, "LOW"],
];

export function riskScoreLevel(score: number): RiskScoreLevel {
  return (LEVELS.find(([min]) => score >= min) ?? [0, "LOW"])[1];
}

export type RiskFactorKey =
  | "size"
  | "spread"
  | "sensitive"
  | "patterns"
  | "tests"
  | "shape"
  | "context";

export interface RiskFactor {
  key: RiskFactorKey;
  label: string;
  points: number;
  max: number;
  reasons: string[];
}

export type RuleSeverity = "critical" | "high" | "medium" | "low";

/** 追加された行に当たった危ないパターン */
export interface RiskRuleHit {
  rule: string;
  severity: RuleSeverity;
  points: number;
  message: string;
  /** PR の説明文に当たったときは "(PR description)" */
  file: string;
  line: number;
  snippet: string;
}

export interface RiskAdjustment {
  type: "cap" | "floor";
  value: number;
  reason: string;
}

export interface RiskHotspot {
  path: string;
  reasons: string[];
}

export interface SemanticRiskItem {
  points: number;
  file: string;
  line: string;
  reason: string;
  escalation: boolean;
}

export interface SemanticRisk {
  /** 項目の合計を ±20 に収めた値 */
  adjustment: number;
  items: SemanticRiskItem[];
  escalated: boolean;
  summary: string;
  notes: string[];
}

export interface RiskScore {
  /** 最終の点数（0〜100） */
  score: number;
  /** 決定的な基準点。AI の補正を入れる前の点 */
  baseline: number;
  level: RiskScoreLevel;
  threshold: number;
  /** 点数が閾値を超えたか、エスカレーションがあれば true。完全自動運転はこれで人に回す */
  needsHuman: boolean;
  factors: RiskFactor[];
  findings: RiskRuleHit[];
  adjustments: RiskAdjustment[];
  hotspots: RiskHotspot[];
  /** AI の補正。AI レビューをまだしていない、または AI が書かなかったときは null */
  semantic: SemanticRisk | null;
}

export interface RiskScoreInput {
  files: readonly DiffFile[];
  title: string;
  body: string;
  draft: boolean;
  authorIsBot: boolean;
  /** 採点に数えないパスの正規表現（自動運転の設定の ignoredPaths） */
  ignoredPaths: readonly string[];
  threshold: number;
}

