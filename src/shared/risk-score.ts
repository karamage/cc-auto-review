/**
 * diff と PR の情報だけから決まる基準点。AI を呼ばないので、PR を開いた時点で出せる。
 * 作成者が初めての貢献者かは gh pr view から取れないため、スキルと違って見ない
 */
export function computeBaselineRisk(input: RiskScoreInput, lang: Lang): RiskScore {
  const files = input.files.map((file) => classify(file, input.ignoredPaths));
  const effective = files.filter((f) => !(f.ignored || f.lockfile || f.generated));
  // 文章の間違いはコードより安いので、文書の行は 1/5 に数える
  const effectiveLines = Math.round(
    effective.reduce((sum, f) => sum + (f.additions + f.deletions) * (f.doc ? 0.2 : 1), 0),
  );
  const totalAdd = files.reduce((sum, f) => sum + f.additions, 0);
  const totalDel = files.reduce((sum, f) => sum + f.deletions, 0);

  const factors = Object.fromEntries(
    FACTOR_KEYS.map((key) => [key, { points: 0, reasons: [] as string[] }]),
  ) as Record<RiskFactorKey, { points: number; reasons: string[] }>;
  const fileRisk = new Map<string, { points: number; reasons: string[] }>();
  const bump = (path: string, points: number, why: string): void => {
    const entry = fileRisk.get(path) ?? { points: 0, reasons: [] };
    entry.points += points;
    if (!entry.reasons.includes(why)) entry.reasons.push(why);
    fileRisk.set(path, entry);
  };

  // 1. 規模
  factors.size.points = step(effectiveLines, [
    [10, 0],
    [50, 3],
    [150, 6],
    [300, 10],
    [600, 14],
    [1000, 17],
    [Number.POSITIVE_INFINITY, 20],
  ]);
  const excluded = files.length - effective.length;
  factors.size.reasons.push(
    L(
      lang,
      `実質 ${effectiveLines} 行の変更${excluded > 0 ? `（ロックファイル・生成物など ${excluded} ファイルは除外）` : ""}`,
      `${effectiveLines} effective lines changed${excluded > 0 ? ` (${excluded} lockfile/generated/ignored files excluded)` : ""}`,
    ),
  );

  // 2. 広がり
  const topDirs = new Set(
    effective.map((f) => (f.path.includes("/") ? f.path.split("/")[0] : ".")),
  );
  let spread = step(effective.length, [
    [3, 0],
    [10, 2],
    [20, 4],
    [40, 6],
    [Number.POSITIVE_INFINITY, 8],
  ]);
  if (topDirs.size >= 4) spread += 2;
  factors.spread.points = Math.min(spread, FACTOR_MAX.spread);
  factors.spread.reasons.push(
    L(
      lang,
      `${effective.length} ファイル、トップレベルの ${topDirs.size} ディレクトリにまたがる`,
      `${effective.length} files across ${topDirs.size} top-level directories`,
    ),
  );

  // 3. 影響の大きい領域
  const hitCategories = new Map<SensitiveCategory, string[]>();
  for (const f of files) {
    if (f.ignored) continue;
    const lower = f.path.toLowerCase();
    for (const category of SENSITIVE_CATEGORIES) {
      // 文書は数えない。ただしレビュアーやエージェントを動かすファイルは数える
      if (f.doc && category.name !== "governance") continue;
      // 認証のテストは認証の変更ではない
      if (f.test && category.name !== "infrastructure" && category.name !== "governance") continue;
      if (category.re.test(lower)) {
        hitCategories.set(category.name, [...(hitCategories.get(category.name) ?? []), f.path]);
      }
    }
  }
  const lockfiles = files.filter((f) => f.lockfile && !f.ignored).map((f) => f.path);
  let sensitive = 0;
  for (const category of SENSITIVE_CATEGORIES) {
    const paths = hitCategories.get(category.name);
    if (paths === undefined) continue;
    sensitive += category.points;
    const label = lang === "en" ? category.en : category.ja;
    factors.sensitive.reasons.push(`${label} (+${category.points}): ${listPaths(paths)}`);
    for (const path of paths) bump(path, category.points, label);
  }
  if (lockfiles.length > 0 && !hitCategories.has("dependencies")) {
    sensitive += 3;
    factors.sensitive.reasons.push(
      L(
        lang,
        `ロックファイルだけの依存関係の更新 (+3): ${listPaths(lockfiles)}`,
        `lockfile-only dependency update (+3): ${listPaths(lockfiles)}`,
      ),
    );
  }
  factors.sensitive.points = Math.min(sensitive, FACTOR_MAX.sensitive);

  // 4. 危ないパターン（追加された行だけを見る）
  const findings: RiskRuleHit[] = [];
  const fired = new Map<string, { rule: Rule; count: number }>();
  const message = (rule: Rule): string => (lang === "en" ? rule.en : rule.ja);
  let scanned = 0;
  for (const f of files) {
    if (f.ignored || f.lockfile) continue;
    const lines = f.added.slice(0, Math.max(0, MAX_SCANNED_LINES - scanned));
    scanned += lines.length;
    if (lines.length === 0) continue;
    for (const rule of RULES) {
      if (rule.scope === "code" && (f.test || f.doc || f.generated)) continue;
      if (rule.scope === "nondoc" && (f.test || f.doc)) continue;
      if (rule.scope === "workflow" && !f.workflow) continue;
      if (f.generated && rule.scope !== "all") continue;
      for (const { line, text } of lines) {
        if (text.length > MAX_LINE_LENGTH || !rule.re.test(text)) continue;
        const secret = rule.id.startsWith("secret") || rule.id === "hardcoded-credential";
        findings.push({
          rule: rule.id,
          severity: rule.severity,
          points: rule.points,
          message: message(rule),
          file: f.path,
          line,
          snippet: secret ? redact(truncate(text)) : truncate(text),
        });
        const entry = fired.get(rule.id) ?? { rule, count: 0 };
        entry.count++;
        fired.set(rule.id, entry);
        bump(f.path, rule.points, message(rule));
      }
    }
  }
  // PR の説明文にも、AI のレビュアーを操ろうとする文が入りうる
  const injection = RULES.find((rule) => rule.id === "prompt-injection") as Rule;
  const bodyLines = input.body.split(/\r?\n/);
  const injected = bodyLines.findIndex((text) => injection.re.test(text));
  if (injected >= 0) {
    findings.push({
      rule: injection.id,
      severity: injection.severity,
      points: injection.points,
      message: `${message(injection)}${L(lang, "（PR の説明文）", " in PR description")}`,
      file: "(PR description)",
      line: injected + 1,
      snippet: truncate(bodyLines[injected] ?? ""),
    });
    const entry = fired.get(injection.id) ?? { rule: injection, count: 0 };
    entry.count++;
    fired.set(injection.id, entry);
  }
  let patterns = 0;
  for (const { rule, count } of [...fired.values()].sort(
    (a, b) =>
      SEVERITY_ORDER[a.rule.severity] - SEVERITY_ORDER[b.rule.severity] ||
      a.rule.id.localeCompare(b.rule.id),
  )) {
    patterns += rule.points;
    factors.patterns.reasons.push(
      `${message(rule)} [${rule.severity}] ×${count} (+${rule.points})`,
    );
  }
  factors.patterns.points = Math.min(patterns, FACTOR_MAX.patterns);
  findings.sort(
    (a, b) =>
      SEVERITY_ORDER[a.severity] - SEVERITY_ORDER[b.severity] ||
      a.file.localeCompare(b.file) ||
      a.line - b.line,
  );

  // 5. テストの不足
  const codeLines = effective
    .filter((f) => f.code)
    .reduce((sum, f) => sum + f.additions + f.deletions, 0);
  const testFiles = files.filter((f) => f.test && !f.ignored);
  const testAdd = testFiles.reduce((sum, f) => sum + f.additions, 0);
  const testDel = testFiles.reduce((sum, f) => sum + f.deletions, 0);
  const testLines = testAdd + testDel;
  let tests = 0;
  if (codeLines >= 20 && testLines === 0) {
    tests = step(codeLines, [
      [99, 6],
      [299, 10],
      [Number.POSITIVE_INFINITY, 15],
    ]);
    factors.tests.reasons.push(
      L(
        lang,
        `コードを ${codeLines} 行変えたが、テストを変えていない`,
        `${codeLines} lines of code changed with no test changes`,
      ),
    );
  } else if (codeLines >= 100 && testLines < codeLines * 0.1) {
    tests = 5;
    factors.tests.reasons.push(
      L(
        lang,
        `テストの変更（${testLines} 行）がコードの変更（${codeLines} 行）の 1 割に満たない`,
        `test changes (${testLines} lines) are <10% of code changes (${codeLines} lines)`,
      ),
    );
  }
  const critical = (["security", "payments", "data_migration"] as const).filter((c) =>
    hitCategories.has(c),
  );
  if (tests > 0 && critical.length > 0) {
    tests += 5;
    factors.tests.reasons.push(
      L(
        lang,
        "テストの無い変更が、認証・決済・マイグレーションに触れている (+5)",
        "untested change touches security / payments / migrations (+5)",
      ),
    );
  }
  const removedTests = testFiles.filter((f) => f.status === "deleted").map((f) => f.path);
  if (removedTests.length > 0 || (testDel > 20 && testDel > testAdd * 2)) {
    tests += 5;
    factors.tests.reasons.push(
      L(
        lang,
        `テストを消した、または減らした（−${testDel}/+${testAdd} 行）`,
        `tests removed or net-shrunk (−${testDel}/+${testAdd} lines)`,
      ),
    );
  }
  if (factors.tests.reasons.length === 0) {
    factors.tests.reasons.push(
      codeLines > 0
        ? L(
            lang,
            `コード ${codeLines} 行に対してテスト ${testLines} 行`,
            `${testLines} test lines for ${codeLines} code lines`,
          )
        : L(lang, "コードの変更が無い", "no code changes"),
    );
  }
  factors.tests.points = Math.min(tests, FACTOR_MAX.tests);

  // 6. 変更の形
  let shape = 0;
  const deletedSources = effective.filter((f) => f.status === "deleted" && !f.test && !f.doc);
  if (deletedSources.length > 0) {
    shape += Math.min(2 * deletedSources.length, 6);
    factors.shape.reasons.push(
      L(
        lang,
        `ソースファイルを ${deletedSources.length} 個消している`,
        `${deletedSources.length} source files deleted`,
      ),
    );
  }
  const binaries = effective.filter((f) => f.binary && !f.doc).map((f) => f.path);
  if (binaries.length > 0) {
    shape += 2;
    factors.shape.reasons.push(
      L(
        lang,
        `バイナリを変えている: ${listPaths(binaries)}`,
        `binary files changed: ${listPaths(binaries)}`,
      ),
    );
  }
  const big = effective.filter((f) => f.additions + f.deletions > 500);
  if (big.length > 0) {
    shape += 3;
    const shown = big
      .slice(0, 2)
      .map((f) => `${f.path} (${f.additions + f.deletions})`)
      .join(", ");
    factors.shape.reasons.push(
      L(
        lang,
        `1 ファイルの変更が非常に大きい: ${shown}`,
        `very large single-file change: ${shown}`,
      ),
    );
    for (const f of big) bump(f.path, 3, L(lang, "非常に大きい変更", "very large change"));
  }
  const renames = files.filter((f) => f.status === "renamed").length;
  if (renames >= 5) {
    shape += 2;
    factors.shape.reasons.push(
      L(lang, `${renames} ファイルの改名・移動`, `${renames} files renamed/moved`),
    );
  }
  if (
    effectiveLines > 400 &&
    totalAdd > 0 &&
    totalDel > 0 &&
    Math.min(totalAdd, totalDel) / Math.max(totalAdd, totalDel) > 0.6
  ) {
    shape += 1;
    factors.shape.reasons.push(
      L(
        lang,
        `大きな書き換え（+${totalAdd}/−${totalDel}）`,
        `heavy rewrite (+${totalAdd}/−${totalDel})`,
      ),
    );
  }
  factors.shape.points = Math.min(shape, FACTOR_MAX.shape);

  // 7. 作成者と経緯
  let context = 0;
  if (input.body.trim().length < 20 && effectiveLines > 50) {
    context += 3;
    factors.context.reasons.push(
      L(lang, "PR の説明文が空かほとんど無い", "PR description is empty or near-empty"),
    );
  }
  const rushed = RUSHED_TITLE_RE.exec(input.title);
  if (rushed !== null) {
    context += 3;
    factors.context.reasons.push(
      L(
        lang,
        `タイトルが急ぎの変更を示している（${rushed[0]}）`,
        `title suggests a rushed change (${rushed[0]})`,
      ),
    );
  }
  if (input.draft || WIP_TITLE_RE.test(input.title)) {
    context += 2;
    factors.context.reasons.push(L(lang, "ドラフト / WIP", "marked as draft / WIP"));
  }
  if (input.authorIsBot)
    factors.context.reasons.push(L(lang, "bot が作った PR", "authored by a bot"));
  if (factors.context.reasons.length === 0) {
    factors.context.reasons.push(L(lang, "経緯に気になる点は無い", "no contextual risk signals"));
  }
  factors.context.points = Math.min(context, FACTOR_MAX.context);

  // 合計と、上限・下限
  const raw = FACTOR_KEYS.reduce((sum, key) => sum + factors[key].points, 0);
  let score = Math.min(raw, 100);
  const adjustments: RiskAdjustment[] = [];
  const hasSecret = findings.some((f) => f.rule.startsWith("secret-"));
  const counted = files.filter((f) => !f.ignored);
  const governance = hitCategories.has("governance");

  if (
    counted.length > 0 &&
    counted.every((f) => f.doc) &&
    !hasSecret &&
    !fired.has("prompt-injection") &&
    !governance
  ) {
    if (score > 10) {
      adjustments.push({
        type: "cap",
        value: 10,
        reason: L(lang, "文書だけの変更", "documentation-only change"),
      });
      score = 10;
    }
  } else if (
    counted.length > 0 &&
    counted.every((f) => f.doc || f.test) &&
    !hasSecret &&
    !governance
  ) {
    if (score > 20) {
      adjustments.push({
        type: "cap",
        value: 20,
        reason: L(lang, "テストと文書だけの変更", "tests/docs-only change"),
      });
      score = 20;
    }
  }

  const floors: [number, string][] = [];
  if (hasSecret) {
    floors.push([
      90,
      L(
        lang,
        "diff に秘密情報が含まれる。履歴を書き換えるだけでは足りず、無効化が要る",
        "a secret/credential appears in the diff — rotate it, rewriting history is not enough",
      ),
    ]);
  }
  const migration = SENSITIVE_CATEGORIES.find((c) => c.name === "data_migration") as {
    re: RegExp;
  };
  if (
    findings.some((f) => f.rule === "destructive-sql" && migration.re.test(f.file.toLowerCase()))
  ) {
    floors.push([
      75,
      L(
        lang,
        "データを壊すマイグレーション（失ったデータは戻せない）",
        "destructive database migration (data loss is irreversible)",
      ),
    ]);
  }
  if (fired.has("workflow-pull-request-target")) {
    floors.push([
      60,
      L(lang, "特権のあるワークフローのトリガーを足している", "privileged workflow trigger added"),
    ]);
  }
  if (fired.has("prompt-injection")) {
    floors.push([
      60,
      L(
        lang,
        "AI のレビュアーを操ろうとする内容がある。自動で承認してはいけない",
        "content attempts to steer AI reviewers; a human must decide",
      ),
    ]);
  }
  for (const [value, reason] of floors) {
    if (score < value) {
      adjustments.push({ type: "floor", value, reason });
      score = value;
    }
  }

  const hotspots: RiskHotspot[] = [...fileRisk.entries()]
    .sort((a, b) => b[1].points - a[1].points)
    .slice(0, 8)
    .map(([path, entry]) => ({ path, reasons: entry.reasons }));
  if (hotspots.length < 3) {
    // どの規則も当たらなくても、AI がどこから読むかの手がかりにする
    const seen = new Set(hotspots.map((h) => h.path));
    const biggest = effective
      .filter((f) => f.code && !seen.has(f.path))
      .sort((a, b) => b.additions + b.deletions - (a.additions + a.deletions));
    for (const f of biggest.slice(0, 3 - hotspots.length)) {
      hotspots.push({
        path: f.path,
        reasons: [
          L(
            lang,
            `いちばん大きいコードの変更（+${f.additions}/−${f.deletions}）。規則は当たらないので、振る舞いを読む`,
            `largest code change (+${f.additions}/−${f.deletions}); no rule fired, review for behavior`,
          ),
        ],
      });
    }
  }

  const threshold = input.threshold;
  return {
    score,
    baseline: score,
    level: riskScoreLevel(score),
    threshold,
    needsHuman: score > threshold,
    factors: FACTOR_KEYS.map((key) => ({
      key,
      label: FACTOR_LABEL[key][lang],
      points: factors[key].points,
      max: FACTOR_MAX[key],
      reasons: factors[key].reasons,
    })),
    findings: findings.slice(0, 50),
    adjustments,
    hotspots,
    semantic: null,
  };
}

// ---------------------------------------------------------------------------
// AI の補正
// ---------------------------------------------------------------------------

/**
 * AI が書いた補正の項目を基準点に足す。AI は項目を出すだけで、点の計算はここでする。
 * 1 項目は ±15、合計は ±20 に収め、下限（floor）は下回らせない。
 * 引用付きのエスカレーションがあれば 60 点以上にして必ず人に回す。
 * 読めない値は補正が無かったものとして基準点をそのまま返す
 */
export function applySemanticRisk(base: RiskScore, raw: unknown, lang: Lang): RiskScore {
  const value = raw as { items?: unknown; summary?: unknown } | null;
  if (value === null || typeof value !== "object" || !Array.isArray(value.items)) return base;

  const items: SemanticRiskItem[] = [];
  for (const entry of value.items.slice(0, 20)) {
    const item = entry as Record<string, unknown> | null;
    if (item === null || typeof item !== "object") continue;
    const points = Number(item.points);
    if (!Number.isFinite(points)) continue;
    const reason = truncate(String(item.reason ?? ""), 300);
    const file = truncate(String(item.file ?? ""), 200);
    // 引用の無い項目は数えない
    if (reason === "" || file === "") continue;
    const clamped = clamp(Math.trunc(points), -SEMANTIC_ITEM_MAX, SEMANTIC_ITEM_MAX);
    items.push({
      points: clamped,
      file,
      line: truncate(String(item.line ?? ""), 20),
      reason,
      escalation: item.escalation === true && clamped > 0,
    });
  }

  const notes: string[] = [];
  const rawAdjustment = items.reduce((sum, item) => sum + item.points, 0);
  const adjustment = clamp(rawAdjustment, -SEMANTIC_TOTAL_MAX, SEMANTIC_TOTAL_MAX);
  if (adjustment !== rawAdjustment) {
    notes.push(
      L(
        lang,
        `補正の合計 ${signed(rawAdjustment)} を ${signed(adjustment)} に収めた`,
        `semantic items summed to ${signed(rawAdjustment)}, clamped to ${signed(adjustment)}`,
      ),
    );
  }
  const floor = Math.max(
    0,
    ...base.adjustments.filter((a) => a.type === "floor").map((a) => a.value),
  );
  let score = clamp(base.baseline + adjustment, floor, 100);
  if (base.baseline + adjustment < floor) {
    notes.push(L(lang, `下限の ${floor} 点で止めた`, `held at floor ${floor}`));
  }
  const escalated = items.filter((item) => item.escalation);
  if (escalated.length > 0 && score < ESCALATION_FLOOR) {
    notes.push(
      L(
        lang,
        `エスカレーションのため ${ESCALATION_FLOOR} 点に引き上げた: ${escalated[0]?.reason ?? ""}`,
        `escalated to ${ESCALATION_FLOOR}: ${escalated[0]?.reason ?? ""}`,
      ),
    );
    score = ESCALATION_FLOOR;
  }

  return {
    ...base,
    score,
    level: riskScoreLevel(score),
    needsHuman: score > base.threshold || escalated.length > 0,
    semantic: {
      adjustment,
      items,
      escalated: escalated.length > 0,
      summary: truncate(String(value.summary ?? ""), 300),
      notes,
    },
  };
}

function signed(n: number): string {
  return n > 0 ? `+${n}` : String(n);
}

/** AI に補正を頼むときに渡す、基準点の要約。何がすでに数えられているかを伝え、二重に数えさせない */
export function describeBaselineForPrompt(risk: RiskScore): string {
  const factors = risk.factors
    .filter((f) => f.points > 0)
    .map((f) => `- ${f.key} +${f.points}/${f.max}: ${f.reasons.join("; ")}`);
  const hotspots = risk.hotspots.map((h) => `- ${h.path}: ${h.reasons.join("; ")}`);
  const floors = risk.adjustments.map((a) => `- ${a.type} ${a.value}: ${a.reason}`);
  return [
    `Baseline score: ${risk.baseline}/100 (threshold ${risk.threshold}; above it a human must review)`,
    factors.length > 0
      ? `Factors already counted:\n${factors.join("\n")}`
      : "No factor added points.",
    hotspots.length > 0 ? `Hotspots (start reading here):\n${hotspots.join("\n")}` : "",
    floors.length > 0 ? `Caps and floors:\n${floors.join("\n")}` : "",
  ]
    .filter((part) => part !== "")
    .join("\n\n");
}
