// サイトのリスク採点（docs/engine.js）を src の採点コードから作る
const result = await Bun.build({
  entrypoints: ["scripts/site-engine.ts"],
  target: "browser",
  format: "iife",
  minify: true,
  naming: "engine.js",
  outdir: "docs",
  banner: "// Generated by scripts/build-site.ts from src/shared/risk-score.ts. Do not edit.",
});
if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}
